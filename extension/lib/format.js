// Small formatting / parsing helpers shared by popup, background and tests.

export function formatClock(sec) {
  if (sec === null || sec === undefined || !Number.isFinite(sec)) return '';
  const s = Math.max(0, Math.floor(sec));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const r = String(s % 60).padStart(2, '0');
  return h ? `${h}:${String(m).padStart(2, '0')}:${r}` : `${m}:${r}`;
}

export function formatDuration(ms) {
  if (!Number.isFinite(ms) || ms <= 0) return '';
  const min = Math.ceil(ms / 60000);
  if (min < 60) return `${min} min`;
  const h = Math.floor(min / 60);
  const m = min % 60;
  return m ? `${h} h ${m} min` : `${h} h`;
}

/**
 * Parse a pasted transcript. Accepts YouTube's "Show transcript" copy format
 * (timestamp on its own line followed by text), "0:12 text", "[00:12] text",
 * SRT/VTT-ish "00:00:12,000 --> ..." blocks, or plain text without times.
 */
export function parsePastedTranscript(input) {
  const text = String(input ?? '').replace(/\r\n?/g, '\n').slice(0, 600_000);
  const lines = text.split('\n').map((l) => l.trim()).filter((l) => l && l !== 'WEBVTT' && !/^\d+$/.test(l));
  const clock = /^\[?((?:\d{1,2}:)?\d{1,2}:\d{2})(?:[.,]\d{1,3})?\]?(?:\s*-->\s*\S+)?\s*(.*)$/;
  const toSec = (c) => c.split(':').reduce((a, p) => a * 60 + Number(p), 0);
  const segs = [];
  let pending = null;
  let timed = 0;
  for (const line of lines) {
    const m = clock.exec(line);
    if (m) {
      timed++;
      if (pending && pending.text) segs.push(pending);
      pending = { start: toSec(m[1]), text: m[2] || '' };
    } else if (pending) {
      pending.text = pending.text ? `${pending.text} ${line}` : line;
    } else {
      segs.push({ start: null, text: line });
    }
  }
  if (pending && pending.text) segs.push(pending);
  // Plain prose: chunk into ~400 char paragraphs so the payload stays tidy.
  if (timed === 0) {
    const words = lines.join(' ').split(/\s+/).filter(Boolean);
    const out = [];
    let cur = '';
    for (const w of words) {
      if (cur.length + w.length + 1 > 400) { out.push({ start: null, text: cur }); cur = w; } else cur = cur ? `${cur} ${w}` : w;
    }
    if (cur) out.push({ start: null, text: cur });
    return out;
  }
  return segs.filter((s) => s.text.trim()).map((s) => ({ start: s.start, text: s.text.trim().slice(0, 5000) }));
}

export function summaryToMarkdown(job) {
  const r = job.result;
  if (!r) return '';
  const lines = [`## ${job.meta?.title || job.videoId}`, ''];
  if (r.source === 'metadata') lines.push('_Metadata only (title/description) — not a summary of the video itself._', '');
  lines.push(r.summary, '');
  if (r.keypoints?.length) {
    lines.push('### Key points');
    for (const k of r.keypoints) {
      const t = k.start !== null && k.start !== undefined
        ? `[${formatClock(k.start)}](https://www.youtube.com/watch?v=${job.videoId}&t=${Math.floor(k.start)}s) ` : '';
      lines.push(`- ${t}${k.text}`);
    }
  }
  lines.push('', `_Generated by ${r.model} via the Gemini API (Preyt)._`);
  return lines.join('\n');
}
