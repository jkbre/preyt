// Pure mapping from a job snapshot to what the popup shows. Kept DOM-free so the
// labelling rules (e.g. metadata is never presented as a video summary) are testable.
import { formatClock, formatDuration } from './format.js';
import { S } from './controller.js';
import { thumbnailUrl } from './youtube-url.js';

const STAGE_LABEL = {
  page: 'Reading the transcript from this tab…',
  tab: 'Reading the transcript in a muted background tab…',
};

const REASONS = {
  no_captions: 'YouTube lists no captions for this video.',
  empty_panel: 'The transcript panel was empty.',
  no_transcript_button: 'The page has no “Show transcript” button.',
  panel_empty: 'The transcript panel stayed empty in the background tab.',
  panel_missing: 'YouTube did not offer a transcript for this video.',
  video_mismatch: 'The YouTube tab switched to a different video, so its transcript was not used.',
  missing_options: 'The YouTube tab navigated while Preyt was reading it; nothing was used. Try again.',
};

export const PROVIDER_NAME = 'Google’s Gemini API (generativelanguage.googleapis.com)';

const ERROR_TITLES = {
  no_api_key: 'Gemini API key needed',
  invalid_api_key: 'API key rejected',
  permission_denied: 'API key not allowed',
  unknown_model: 'Model not available',
  rate_limited: 'Gemini limit reached',
  network_error: 'Cannot reach Gemini',
  provider_unavailable: 'Gemini is busy',
  blocked: 'Gemini declined',
};

export function captionLabel(kind) {
  return kind === 'asr' ? 'auto-generated captions' : kind === 'manual' ? 'creator captions' : 'captions';
}

export function sourceBadge(result, transcript) {
  if (!result) return null;
  if (result.source === 'metadata') {
    return {
      kind: 'metadata',
      label: 'Metadata only',
      warning: 'No transcript was available. This is based only on the title, description and chapters — it is not a summary of what is said in the video.',
    };
  }
  if (result.source === 'pasted') return { kind: 'pasted', label: 'From pasted transcript', warning: null };
  const cov = result.truncated ? ` · ${Math.round((result.coverage ?? 1) * 100)}% of transcript sampled` : '';
  return { kind: 'transcript', label: `From transcript (${captionLabel(transcript?.captionKind)})${cov}`, warning: null };
}

export function viewModel(snapshot, settings = {}) {
  const job = snapshot?.current;
  const recent = (snapshot?.recent ?? []).filter((r) => r.id !== job?.id && r.status === S.DONE);
  if (!job) return { state: 'empty', recent };

  const header = {
    title: job.meta?.title || 'YouTube video',
    channel: job.meta?.channel || '',
    duration: job.meta?.durationSec ? formatClock(job.meta.durationSec) : '',
    thumbnail: settings.showThumbnails === false ? '' : thumbnailUrl(job.videoId),
    url: job.url,
  };
  const base = { jobId: job.id, header, recent };
  const modelName = settings.model || 'the selected Gemini model';

  switch (job.status) {
    case S.CONSENT:
      return {
        ...base,
        state: 'consent',
        consent: {
          intro: 'Summaries are generated by Google’s Gemini, using your own API key. Before anything is sent, here is exactly what happens:',
          items: [
            `The video’s transcript (or, if you choose, its title/description), title, channel and chapter titles are sent directly from this browser to ${PROVIDER_NAME}, using ${modelName}.`,
            'With a free-tier key, Google may use what you send to improve its products, and people may review it. Do not summarize private or unlisted videos you would not share.',
            'Requests count against your key’s quota (and billing, if you enabled it).',
            'Nothing is sent until you press “Send & summarize”.',
          ],
          rememberDefault: true,
        },
      };
    case S.TRANSCRIPT:
    case S.SUMMARIZING: {
      const fetching = job.status === S.TRANSCRIPT;
      const firstStep = job.source === 'metadata' ? { label: 'Title & description', detail: '' }
        : job.source === 'pasted' ? { label: 'Pasted transcript', detail: '' }
          : { label: 'Transcript', detail: !fetching && job.transcript ? `${job.transcript.segments} lines` : '' };
      return {
        ...base,
        state: 'loading',
        startedAt: job.startedAt ?? job.createdAt,
        loading: {
          label: fetching ? (STAGE_LABEL[job.stage] ?? 'Getting the transcript…') : `Summarizing with ${job.stage || 'Gemini'}…`,
          steps: [
            { ...firstStep, state: fetching ? 'active' : 'done' },
            { label: 'Summary', state: fetching ? 'pending' : 'active', detail: '' },
          ],
        },
      };
    }
    case S.NO_TRANSCRIPT:
      return {
        ...base,
        state: 'no-transcript',
        noTranscript: {
          message: REASONS[job.transcript?.reason] ?? 'No transcript could be retrieved for this video.',
          details: job.transcript?.problems ?? [],
          canMetadata: Boolean(job.meta?.title || job.meta?.description),
          metadataLabel: 'Summarize title & description only',
          metadataHint: 'Clearly labelled as metadata — not a video summary.',
        },
      };
    case S.DONE: {
      const r = job.result;
      return {
        ...base,
        state: 'done',
        result: {
          badge: sourceBadge(r, job.transcript),
          summary: r.summary,
          keypoints: (r.keypoints ?? []).map((k) => ({
            seconds: Number.isFinite(k.start) ? k.start : null,
            time: Number.isFinite(k.start) ? formatClock(k.start) : '',
            text: k.text,
          })),
          footer: [r.model, r.elapsedMs ? `${(r.elapsedMs / 1000).toFixed(1)} s` : '', 'via Gemini API'].filter(Boolean).join(' · '),
        },
      };
    }
    case S.ERROR: {
      const e = job.error ?? {};
      let message = e.message || 'Something went wrong.';
      if (e.code === 'rate_limited' && /\blimit:\s*0\b/.test(e.detail ?? '')) {
        message = 'Your key has no free quota for this model. Pick a different model in Options, or enable billing for the key in Google AI Studio.';
      } else if (e.code === 'rate_limited') {
        // Free-tier limits are per model, so a different model may still have quota left.
        const wait = e.retryAfterMs ? `Try again in about ${formatDuration(e.retryAfterMs)}` : 'Wait a minute, then press Try again';
        message += ` ${wait}, or pick a different model in Options (free-tier limits are counted per model). Summaries you already made in this session stay available.`;
      } else if (e.detail && e.detail !== message && /^http_/.test(e.code ?? '')) {
        message += ` (${e.detail})`;
      }
      return {
        ...base,
        state: 'error',
        error: {
          title: ERROR_TITLES[e.code] ?? 'Could not summarize',
          message,
          code: e.code,
          retryable: e.retryable !== false,
          needsOptions: Boolean(e.needsOptions),
        },
      };
    }
    case S.CANCELLED:
    default:
      return { ...base, state: 'cancelled' };
  }
}
